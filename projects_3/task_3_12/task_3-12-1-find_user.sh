#!/bin/bash

echo "Поиск информации о пользователе: $USER"
echo "-----------------------------------"

grep "^$USER:" /etc/passwd

if [ $? -eq 0 ]; then
    echo "-----------------------------------"
    echo "Пользователь найден!"
else
    echo "-----------------------------------"
    echo "Пользователь $USER не найден в /etc/passwd"
fi
