#!/bin/bash

CSV_FILE="data.csv"

if [ ! -f "$CSV_FILE" ]; then
    echo "Ошибка: Файл $CSV_FILE не найден!"
    exit 1
fi

echo "========================================="
echo "Анализ товаров"
echo "========================================="

echo "1. Названия товаров:"
echo "-----------------------------------------"
cut -d ',' -f 2 "$CSV_FILE"
echo ""

echo "2. Товары дороже 20:"
echo "-----------------------------------------"
awk -F ',' '$3 > 20 {print $2 " - " $3 "$"}' "$CSV_FILE"
echo ""

echo "3. Общая стоимость:"
echo "-----------------------------------------"
SUM=$(awk -F ',' '{sum+=$3} END {print sum}' "$CSV_FILE")
echo "Общая стоимость: $SUM $"
echo ""

echo "4. Товары дешевле 10 (дополнительно):"
echo "-----------------------------------------"
awk -F ',' '$3 < 10 {print $2 " - " $3 "$"}' "$CSV_FILE"
if [ -z "$(awk -F ',' '$3 < 10 {print $0}' "$CSV_FILE")" ]; then
    echo "Нет товаров дешевле 10"
fi

echo ""
echo "========================================="
