#!/bin/bash

echo "========================================="
echo "Анализ использования дискового пространства"
echo "========================================="
echo ""

printf "%-20s %-10s %s\n" "Файловая система" "Использовано %" "Статус"
echo "-----------------------------------------"

df -h | awk 'NR > 1 {  # Пропускаем заголовок (первую строку)
    # Удаляем символ % из пятого столбца
    gsub(/%/, "", $5)
    
    # Выводим название ФС (1-й столбец) и процент заполнения (5-й столбец)
    if ($5 > 90) {
        printf "%-20s %-10s %s\n", $1, $5"%", "КРИТИЧЕСКИЙ!"
    } else if ($5 > 75) {
        printf "%-20s %-10s %s\n", $1, $5"%", "Внимание!"
    } else {
        printf "%-20s %-10s %s\n", $1, $5"%", "OK"
    }
}'

echo "========================================="
